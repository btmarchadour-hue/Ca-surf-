export function getSmartWaveDefaults(level: SurferLevel, board: BoardType): {
  minWaveHeight: number;
  maxWaveHeight: number;
  maxWindSpeed: number;
} {
  const baseByLevel: Record<SurferLevel, { min: number; max: number; wind: number }> = {
    beginner: { min: 0.5, max: 1.3, wind: 18 },
    intermediate: { min: 0.8, max: 1.9, wind: 22 },
    advanced: { min: 1.1, max: 2.8, wind: 26 },
    expert: { min: 1.4, max: 4.0, wind: 30 },
  };
  const base = { ...baseByLevel[level] };
  if (board === 'longboard') {
    base.min = Math.max(0.4, Number((base.min - 0.2).toFixed(1)));
    base.max = Math.min(2.0, base.max);
  } else if (board === 'shortboard') {
    base.min = Number((base.min + 0.1).toFixed(1));
  }
  return {
    minWaveHeight: base.min,
    maxWaveHeight: base.max,
    maxWindSpeed: base.wind,
  };
}

